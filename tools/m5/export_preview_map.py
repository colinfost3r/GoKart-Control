#!/usr/bin/env python3
"""Export a small shop background from the SAME OSM extract used by the Pi map.

Demo artwork only, never a driving route. Standard library; no network or devices.
Run from any directory; generated geometry is ODbL 1.0, with attribution in the UI.
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LAT, LON, HALF = 41.0938, -73.4163, 120.0
COS = math.cos(math.radians(LAT))


def clip(a, b):
    dx, dy = b[0]-a[0], b[1]-a[1]
    lo, hi = 0.0, 1.0
    for p, q in ((-dx, a[0]+HALF), (dx, HALF-a[0]),
                 (-dy, a[1]+HALF), (dy, HALF-a[1])):
        if not p:
            if q < 0:
                return None
            continue
        r = q/p
        if p < 0:
            lo = max(lo, r)
        else:
            hi = min(hi, r)
        if lo > hi:
            return None
    return [round(v*10) for v in (a[0]+lo*dx, a[1]+lo*dy, a[0]+hi*dx, a[1]+hi*dy)]


def export():
    doc = json.loads((ROOT/'pit/server/map/sono-map.geojson').read_text())
    lines = []
    for kind, code in (('water', 0), ('coastline', 0), ('building', 1), ('road', 2), ('rail', 3)):
        for f in doc['features']:
            if f['properties']['kind'] != kind:
                continue
            g = f['geometry']
            rings = g['coordinates'] if g['type'] == 'Polygon' else [g['coordinates']]
            for ring in rings:
                pts = [((lon-LON)*111320*COS, (lat-LAT)*111320) for lon, lat in ring]
                for a, b in zip(pts, pts[1:]):
                    s = clip(a, b)
                    if s and s[:2] != s[2:]:
                        lines.append('{'+','.join(map(str, [*s, code]))+'},')
    header = '// Generated by tools/m5/export_preview_map.py; do not hand edit.\n'
    header += '// Shop crop, east/north decimetres from 41.0938, -73.4163.\n'
    header += '// Map data (c) OpenStreetMap contributors; ODbL 1.0.\n'
    header += '// Source and license: pit/server/map/SONO-MAP.md and sono-map.geojson.\n'
    dest = ROOT/'firmware/m5-core2/preview_shop_lines.inc'
    dest.write_text(header+'\n'.join(lines)+'\n')
    print(f'{len(lines)} clipped map segments -> {dest}')


if __name__ == '__main__':
    export()
