#!/usr/bin/env python3
"""Export the built-in street lines the Core2 draws under its live map.

One table per site, cut from OpenStreetMap extracts already in this repository. The lines
are context only: never a driving route, a course or a position. Standard library; no
network, no devices. Generated geometry is ODbL 1.0, with attribution on the Core2 startup
screen. Run from any directory; `--check` compares without writing.
"""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT/'firmware/m5-core2/site_lines.inc'
# kind -> drawing code used by SiteMap::stroke. Water, shore and piers share one quiet ink.
CODES = (('water', 0), ('coastline', 0), ('pier', 0), ('building', 1), ('road', 2), ('rail', 3))
MAX_LINES = 6000    # per site; the Core2 culls with integer compares before any drawing
# key, name shown on the no-GPS overview, source, origin, half extent east/north (m),
# vertical span of the overview (m). Sites must not overlap.
SITES = (
    ('shop', 'SHOP', 'pit/server/map/sono-map.geojson', 41.0938, -73.4163, 300, 300, 240),
    ('manresa', 'MANRESA', 'pit/server/map/manresa-map.geojson', 41.0748, -73.4101, 750, 750, 1300),
)


def clip(a, b, half_east, half_north):
    """Liang-Barsky clip of segment a-b (metres) to the site rectangle; decimetres or None."""
    dx, dy = b[0]-a[0], b[1]-a[1]
    lo, hi = 0.0, 1.0
    for p, q in ((-dx, a[0]+half_east), (dx, half_east-a[0]),
                 (-dy, a[1]+half_north), (dy, half_north-a[1])):
        if not p:
            if q < 0:
                return None
            continue
        r = q/p
        if p < 0:
            lo = max(lo, r)
        else:
            hi = min(hi, r)
        if lo > hi:
            return None
    return tuple(round(v*10) for v in (a[0]+lo*dx, a[1]+lo*dy, a[0]+hi*dx, a[1]+hi*dy))


def site_lines(doc, lat, lon, half_east, half_north):
    cosine = math.cos(math.radians(lat))
    lines, seen = [], set()
    for kind, code in CODES:
        for feature in doc['features']:
            if feature['properties'].get('kind') != kind:
                continue
            geometry = feature['geometry']
            if geometry['type'] == 'Polygon':
                rings = geometry['coordinates']
            elif geometry['type'] == 'LineString':
                rings = [geometry['coordinates']]
            else:
                continue
            for ring in rings:
                points = [((x-lon)*111320*cosine, (y-lat)*111320) for x, y in ring]
                for a, b in zip(points, points[1:]):
                    s = clip(a, b, half_east, half_north)
                    if not s or s[:2] == s[2:]:
                        continue
                    # A wall shared by two buildings is stored once.
                    key = (min(s[:2], s[2:]), max(s[:2], s[2:]), code)
                    if key in seen:
                        continue
                    seen.add(key)
                    lines.append((*s, code))
    return lines


def render():
    out = ['// Generated by tools/m5/export_site_maps.py; do not hand edit.',
           '// Built-in street context per site: east/north decimetres from the site origin.',
           '// Map data (c) OpenStreetMap contributors; ODbL 1.0.',
           '// Sources and license: pit/server/map/SONO-MAP.md and pit/server/map/MANRESA-MAP.md.']
    rows, summary = [], {}
    for key, name, source, lat, lon, half_east, half_north, overview in SITES:
        lines = site_lines(json.loads((ROOT/source).read_text()), lat, lon, half_east, half_north)
        if not 0 < len(lines) <= MAX_LINES:
            raise ValueError(f'{key}: {len(lines)} lines is outside 1..{MAX_LINES}')
        if max(half_east, half_north)*10 > 32767:
            raise ValueError(f'{key}: extent does not fit 16-bit decimetres')
        summary[key] = len(lines)
        out.append(f'inline constexpr SiteLine site_{key}[]={{')
        out.extend('{'+','.join(map(str, line))+'},' for line in lines)
        out.append('};')
        rows.append(f'{{"{name}",{lat!r},{lon!r},{half_east*10},{half_north*10},{overview},'
                    f'site_{key},sizeof site_{key}/sizeof *site_{key}}},')
    out.append('inline constexpr Site sites[]={')
    out.extend(rows)
    out.append('};')
    return '\n'.join(out)+'\n', summary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='compare with the committed file; write nothing')
    args = parser.parse_args()
    text, summary = render()
    if args.check:
        same = DEST.exists() and DEST.read_text() == text
        print(json.dumps({'file': str(DEST), 'lines': summary, 'current': same}))
        raise SystemExit(0 if same else 1)
    DEST.write_text(text)
    print(json.dumps({'file': str(DEST), 'lines': summary, 'no_device_opened': True}))


if __name__ == '__main__':
    main()
